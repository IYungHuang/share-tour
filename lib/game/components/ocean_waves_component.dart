  final List<Offset> _points = [];
  final List<int> _phases = [];

  double _timer = 0.0;
  int _globalStep = 0;

  void _initPoints() {
    for (var i = 0; i < _rawCoords.length; i += 2) {
      final x = _rawCoords[i].toDouble();
      final y = _rawCoords[i + 1].toDouble();
      _points.add(Offset(x, y));
      // 依網格位置產生不同相位（0, 1, 2），使波浪錯落起伏而非整齊劃一
      _phases.add((((_rawCoords[i] ~/ 64) * 7 + (_rawCoords[i + 1] ~/ 64) * 13) % 3).abs());
    }
  }

  @override
  void update(double dt) {
    super.update(dt);
    _timer += dt;
    // 每 0.45 秒切換一幀，模擬悠緩的海面波浪節奏
    if (_timer >= 0.45) {
      _timer -= 0.45;
      _globalStep = (_globalStep + 1) % 3;
    }
  }

  @override
  void render(Canvas canvas) {
    super.render(canvas);
    for (var i = 0; i < _points.length; i++) {
      final frame = (_globalStep + _phases[i]) % 3;
      final pt = _points[i];
      canvas.drawImageRect(
        waveImage,
        _srcRects[frame],
        Rect.fromLTWH(pt.dx, pt.dy, 16, 16),
        _paint,
      );
    }
  }
